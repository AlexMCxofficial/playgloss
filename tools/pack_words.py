#!/usr/bin/env python3
"""Packs the word lists into web/js/words.js. MIT License (see LICENSE).

Input : tools/data/words.json and tools/data/words_extreme.json (made by build_words.py)
Output: web/js/words.js  (the only word file the game loads)

Why: the old files were two big object trees (about 2,800 objects and 11,200 strings kept in memory for the whole
session). The pack keeps every distinct sentence once, in a single text, and each word is five small numbers.
The game reads one word at a time (Words.get), so almost nothing is kept in memory.

Run: python3 tools/pack_words.py
"""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = {"n": "tools/data/words.json", "x": "tools/data/words_extreme.json"}
OUT = "web/js/words.js"

HEAD = "var Words = (function (P) {\n"
BODY = r"""  "use strict";
  // Reads the pack. Nothing is decoded until a word is asked for.
  var off = null, cache = {};
  function offsets() {
    if (off) return off;
    var n = 0, i = -1;
    off = new Int32Array(P.c + 1); off[0] = 0;
    while ((i = P.t.indexOf("\n", i + 1)) >= 0) off[++n] = i + 1;
    off[P.c] = P.t.length + 1;
    return off;
  }
  function text(k) { var o = offsets(); return P.t.slice(o[k], o[k + 1] - 1); }
  function rows(id, x) {
    var key = x + id, r = cache[key];
    if (r) return r;
    var s = P[x][id];
    if (!s) return null;
    var p = s.split(","); r = new Uint16Array(p.length);
    for (var i = 0; i < p.length; i++) r[i] = parseInt(p[i], 36);
    return (cache[key] = r);
  }
  // Which list a level really uses: the Extreme list when it has that level, otherwise the normal list.
  function which(id, extreme) { return extreme && P.x[id] ? "x" : "n"; }
  function count(id, extreme) { var r = rows(id, which(id, extreme)); return r ? r.length / 5 : 0; }
  function word(id, extreme, k) { return text(rows(id, which(id, extreme))[k * 5]); }
  function get(id, extreme, k) {
    var r = rows(id, which(id, extreme)), b = k * 5;
    return { word: text(r[b]), meaning: text(r[b + 1]), wrong: [text(r[b + 2]), text(r[b + 3]), text(r[b + 4])] };
  }
  function levels() { return Object.keys(P.n); }
  return { count: count, word: word, get: get, levels: levels };
})("""

def main():
    table, index = [], {}
    def idx(s):
        if "\n" in s:
            sys.exit("a sentence contains a line break: " + repr(s))
        if s not in index:
            index[s] = len(table); table.append(s)
        return index[s]
    pack = {}
    for key, rel in SRC.items():
        with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
            data = json.load(f)
        pack[key] = {}
        for level, entries in data.items():
            flat = []
            for e in entries:
                if len(e["wrong"]) != 3:
                    sys.exit("every word needs exactly 3 wrong meanings: " + e["word"])
                for s in [e["word"], e["meaning"]] + e["wrong"]:
                    flat.append(idx(s))
            pack[key][level] = flat
    if len(table) > 65535:
        sys.exit("too many distinct sentences for 16-bit numbers")

    def b36(n):
        d = "0123456789abcdefghijklmnopqrstuvwxyz"; s = ""
        while True:
            s = d[n % 36] + s; n //= 36
            if not n: return s
    out = ["// Generated by tools/pack_words.py from tools/data/*.json (WordNet words, see CREDITS.md). Do not edit by hand.\n", HEAD, BODY]
    out.append("{\n c: %d,\n t: %s,\n" % (len(table), json.dumps("\n".join(table), ensure_ascii=False)))
    parts = []
    for key in ("n", "x"):
        items = ['  "%s": "%s"' % (lv, ",".join(b36(i) for i in flat)) for lv, flat in pack[key].items()]
        parts.append(" %s: {\n%s\n }" % (key, ",\n".join(items)))
    out.append(",\n".join(parts) + "\n});\n")
    text = "".join(out)
    with open(os.path.join(ROOT, OUT), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("Wrote %s: %d distinct sentences, %d bytes" % (OUT, len(table), len(text.encode("utf-8"))))

main()
